        if ($algorithm === 'woa') {
            return self::generatePythonWOA($populationSize, $maxIterations, $dimension, $lowerBound, $upperBound, $objFuncCode);
        } else {
            return self::generatePythonPSO($populationSize, $maxIterations, $dimension, $lowerBound, $upperBound, $objFuncCode);
        }
    }

